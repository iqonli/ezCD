"""Generate standard provider metadata variants for requested launcher cell spans.
Only default size changes on Android 12+; all instances keep their resize minimum.
"""
from pathlib import Path
import re,sys
root=Path(__file__).resolve().parents[1]
base=(root/'app/src/main/res/xml/countdown_widget_info.xml').read_text()
items=[]
for x in range(1,17):
 for y in range(1,17):
  name=f'pin_size_{x}_{y}'
  items.append(f'            <meta-data android:name="ezcd.widget.size.{x}x{y}" android:resource="@xml/{name}" />')
  for folder,legacy in [('xml',True),('xml-v31',False)]:
   text=base.replace('android:targetCellWidth="1"',f'android:targetCellWidth="{x}"').replace('android:targetCellHeight="1"',f'android:targetCellHeight="{y}"')
   if legacy:text=text.replace('android:minWidth="56dp"',f'android:minWidth="{56+(x-1)*70}dp"').replace('android:minHeight="50dp"',f'android:minHeight="{50+(y-1)*70}dp"')
   text=text.replace('<appwidget-provider','<!-- Copyright (c) 2026 IQ Online Studio. MIT. Generated by tools/generate-pin-sizes.py. -->\n<appwidget-provider',1)
   path=root/f'app/src/main/res/{folder}/{name}.xml'
   if '--check' in sys.argv:assert path.read_text()==text,str(path)
   else:path.parent.mkdir(exist_ok=True);path.write_text(text)
p=root/'app/src/main/AndroidManifest.xml';text=p.read_text()
block='            <!-- BEGIN GENERATED PIN SIZES -->\n'+'\n'.join(items)+'\n            <!-- END GENERATED PIN SIZES -->'
if '<!-- BEGIN GENERATED PIN SIZES -->' in text:
 new=re.sub(r'            <!-- BEGIN GENERATED PIN SIZES -->.*?            <!-- END GENERATED PIN SIZES -->',lambda _:block,text,flags=re.S)
else:new=text.replace('android:resource="@xml/countdown_widget_info" />','android:resource="@xml/countdown_widget_info" />\n'+block)
if '--check' in sys.argv:assert new==text
else:p.write_text(new)
print('Provider size metadata: 1–16 cells per axis, legacy and Android 12+ definitions verified')

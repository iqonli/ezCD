"""Generate parcelable native text appearances, without bundling fonts or libraries.
RemoteViews cannot call setTypeface; Android10+ TextAppearanceSpan carries the font family and variable weight axis.
"""
from pathlib import Path
import sys
r=Path(__file__).resolve().parents[1]
x=['<?xml version="1.0" encoding="utf-8"?>','<!-- Copyright (c) 2026 IQ Online Studio. MIT. Generated by tools/generate-widget-weights.py. -->','<resources xmlns:tools="http://schemas.android.com/tools" tools:targetApi="29">']
for w in range(1,1001):
    family='sans-serif-thin' if w<=200 else 'sans-serif-light' if w<=350 else 'sans-serif-black' if w>=850 else 'sans-serif-medium' if w>=500 else 'sans-serif'
    style='bold' if 650<=w<=849 else 'normal'
    x.append(f'    <style name="ezcd_weight_{w}" parent=""><item name="android:fontFamily">{family}</item><item name="android:textStyle">{style}</item><item name="android:fontVariationSettings">&quot;\'wght\' {w}&quot;</item></style>')
x.append('</resources>')
k=['// Copyright (c) 2026 IQ Online Studio. MIT. Generated by tools/generate-widget-weights.py.','package com.iqonli.ezcd.widget','import com.iqonli.ezcd.R','internal object WidgetWeightStyles {','    val resources=intArrayOf(']
k += ['        '+','.join(f'R.style.ezcd_weight_{w}' for w in range(n,n+10))+',' for n in range(1,1001,10)]
k += ['    )','}']
for p,t in {'app/src/main/res/values/ezcd_font_weights.xml':'\n'.join(x)+'\n','app/src/main/java/com/iqonli/ezcd/widget/WidgetWeightStyles.kt':'\n'.join(k)+'\n'}.items():
 f=r/p
 if '--check' in sys.argv:assert f.read_text()==t,p
 else:f.write_text(t)
print('Widget weights 1–1000 verified' if '--check' in sys.argv else 'Widget weights 1–1000 generated')
